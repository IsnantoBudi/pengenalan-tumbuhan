  // Play a gentle wobble/boing when incorrectly placed
  public playError() {
    if (!this.sfxEnabled) return;
    const ctx = this.getContext();
    if (!ctx) return;

    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = "sawtooth";
    const now = ctx.currentTime;

    osc.frequency.setValueAtTime(220, now);
    osc.frequency.linearRampToValueAtTime(140, now + 0.22);

    gain.gain.setValueAtTime(0.12, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.22);

    // Filter to soften the sawtooth buzz
    const filter = ctx.createBiquadFilter();
    filter.type = "lowpass";
    filter.frequency.setValueAtTime(600, now);

    osc.connect(filter);
    filter.connect(gain);
    gain.connect(ctx.destination);

    osc.start(now);
    osc.stop(now + 0.23);
  }

  // Play a victory fanfare on level completion
  public playFanfare() {
    if (!this.sfxEnabled) return;
    const ctx = this.getContext();
    if (!ctx) return;

    // Duck BGM volume during victory celebration
    if (this.bgmAudio && !this.bgmAudio.paused) {
      this.bgmAudio.volume = 0.05;
      setTimeout(() => {
        if (this.bgmAudio && this.audioEnabled) {
          this.bgmAudio.volume = this.defaultBgmVolume;
        }
      }, 2000);
    }

    const melody = [
      { freq: 523.25, dur: 0.12, delay: 0 },    // C5
      { freq: 659.25, dur: 0.12, delay: 0.12 }, // E5
      { freq: 783.99, dur: 0.12, delay: 0.24 }, // G5
      { freq: 1046.5, dur: 0.45, delay: 0.36 }, // C6
      { freq: 880.0,  dur: 0.15, delay: 0.85 }, // A5
      { freq: 1046.5, dur: 0.6,  delay: 1.02 }, // C6 long
    ];

    const now = ctx.currentTime;

    melody.forEach((note) => {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();

      osc.type = "triangle";
      const start = now + note.delay;

      osc.frequency.setValueAtTime(note.freq, start);

      gain.gain.setValueAtTime(0.2, start);
      gain.gain.exponentialRampToValueAtTime(0.001, start + note.dur);

      osc.connect(gain);
      gain.connect(ctx.destination);

      osc.start(start);
      osc.stop(start + note.dur + 0.05);
      this.activeOscillators.push(osc);
    });
  }

  // Play a soft gliding pencil/brush stroke whoosh
  public playBrushStroke() {
    if (!this.sfxEnabled) return;
    const ctx = this.getContext();
    if (!ctx) return;

    try {
      const now = ctx.currentTime;
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      const filter = ctx.createBiquadFilter();

      osc.type = "sine";
      osc.frequency.setValueAtTime(380, now);
      osc.frequency.exponentialRampToValueAtTime(540, now + 0.08);

      filter.type = "bandpass";
      filter.frequency.setValueAtTime(800, now);
      filter.Q.setValueAtTime(2.5, now);

      gain.gain.setValueAtTime(0.001, now);
      gain.gain.linearRampToValueAtTime(0.08, now + 0.02);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 0.09);

      osc.connect(filter);
      filter.connect(gain);
      gain.connect(ctx.destination);

      osc.start(now);
      osc.stop(now + 0.1);
    } catch {
      // AudioContext fallback
    }
  }

  // Play a joyful, rhythmic children applause and cheering sound effect
  public playApplause() {
    if (!this.sfxEnabled) return;
    const ctx = this.getContext();
    if (!ctx) return;

    try {
      const now = ctx.currentTime;
      const clapCount = 14;

      // Layered synthesized handclaps with varied timing & pitch
      for (let i = 0; i < clapCount; i++) {
        const clapTime = now + (i * 0.08) + (Math.random() * 0.04);
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();
        const filter = ctx.createBiquadFilter();

        osc.type = "triangle";
        const freq = 600 + Math.random() * 800;
        osc.frequency.setValueAtTime(freq, clapTime);
        osc.frequency.exponentialRampToValueAtTime(120, clapTime + 0.045);

        filter.type = "bandpass";
        filter.frequency.setValueAtTime(1200 + Math.random() * 600, clapTime);
        filter.Q.setValueAtTime(1.8, clapTime);

        gain.gain.setValueAtTime(0.18 + Math.random() * 0.08, clapTime);
        gain.gain.exponentialRampToValueAtTime(0.001, clapTime + 0.05);

        osc.connect(filter);
        filter.connect(gain);
        gain.connect(ctx.destination);

        osc.start(clapTime);
        osc.stop(clapTime + 0.06);
        this.activeOscillators.push(osc);
      }

      // Cheerful triumph bells layered on top
      const chimeNotes = [783.99, 1046.5, 1318.51, 1567.98]; // G5, C6, E6, G6
      chimeNotes.forEach((freq, idx) => {
        const chimeStart = now + 0.25 + idx * 0.1;
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();

        osc.type = "sine";
        osc.frequency.setValueAtTime(freq, chimeStart);

        gain.gain.setValueAtTime(0.2, chimeStart);
        gain.gain.exponentialRampToValueAtTime(0.001, chimeStart + 0.45);

        osc.connect(gain);
        gain.connect(ctx.destination);

        osc.start(chimeStart);
        osc.stop(chimeStart + 0.5);
        this.activeOscillators.push(osc);
      });
    } catch {
      // AudioContext fallback
    }
  }

  // Speak Indonesian number clearly
  public speakNumber(num: number) {
    const numberWords: Record<number, string> = {
      1: "Satu",
      2: "Dua",
      3: "Tiga",
      4: "Empat",
      5: "Lima",
      6: "Enam",
      7: "Tujuh",
      8: "Delapan",
      9: "Sembilan",
      10: "Sepuluh",
    };
    const word = numberWords[num] || String(num);
    this.speak(word);
  }

  // Indonesian narration with onEnd callback support
  // 1. Prioritizes studio-quality pre-generated female Indonesian audio clips (100% consistent across all phones/tablets/PCs)
  // 2. Intelligent Web Speech API fallback with strict female voice filter for unexpected dynamic strings
  public speak(text: string, onEnd?: () => void) {
    if (!this.speechEnabled || typeof window === "undefined") {
      if (onEnd) onEnd();
      return;
    }

    // Stop all ongoing sounds, speech & audio clips immediately
    this.stopAll();

    const normKey = this.normalizeTtsKey(text);
    const audioSrc = TTS_AUDIO_MAP[normKey];

    if (audioSrc) {
      try {
        const audio = new Audio(audioSrc);
        audio.preload = "auto";
        this.currentTtsAudio = audio;

        let called = false;
        const safeDone = () => {
          if (!called) {
            called = true;
            if (this.currentTtsAudio === audio) {
              this.currentTtsAudio = null;
            }
            if (onEnd) onEnd();
          }
        };

        audio.onended = safeDone;
        audio.onerror = () => {
          safeDone();
        };

        audio.play().catch(() => {
          safeDone();
        });
        return;
      } catch {
        if (onEnd) onEnd();
        return;
      }
    }

    // Only if not found in pre-generated clips, try Web Speech with verified female voice
    this.speakViaWebSpeech(text, onEnd);
  }

  // Fallback Web Speech API with STRICT Indonesian female voice verification
  // Never speaks with male voice (Microsoft Ardi / default system male voice)
  private speakViaWebSpeech(text: string, onEnd?: () => void) {
    if (typeof window === "undefined" || !("speechSynthesis" in window)) {
      if (onEnd) onEnd();
      return;
    }

    try {
      this.initVoices();

      // Strict enforcement: Only speak if a female Indonesian voice is positively confirmed!
      if (!this.cachedIndonesianFemaleVoice) {
        if (onEnd) onEnd();
        return;
      }

      window.speechSynthesis.cancel();
      const utterance = new SpeechSynthesisUtterance(text);
      utterance.lang = "id-ID";
      utterance.rate = 0.95;
      utterance.pitch = 1.05;
      utterance.voice = this.cachedIndonesianFemaleVoice;

      if (onEnd) {
        let called = false;
        const safeCallback = () => {
          if (!called) {
            called = true;
            onEnd();
          }
        };
        utterance.onend = safeCallback;
        utterance.onerror = safeCallback;
      }

      window.speechSynthesis.speak(utterance);
    } catch {
      if (onEnd) onEnd();
    }
  }

  // Promise-based speak to sequence announcements sequentially
  public speakAsync(text: string): Promise<void> {
    return new Promise((resolve) => {
      this.speak(text, resolve);
    });
  }
